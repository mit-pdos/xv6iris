#!/usr/bin/env python3
"""Generate Xv6Iris/KernelImage.lean: the full loadable xv6 kernel image as a
shared lookup, so proof files import it instead of copying instruction bytes.
Reads the dumper's per-byte (addr,byte) pairs (KernelInstrs.v + KernelData.v) and
emits a BALANCED BISECTION DATA TREE + a generic `lookup` (O(log n) reduction;
the comparison instances are synthesized once in `lookup`, not per node)."""
import re, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
def load(path):
    return re.findall(r'\(\(0x([0-9a-fA-F]+)\)%Z,\s*Z_to_bv 8 \(0x([0-9a-fA-F]+)\)%Z\)', (ROOT/path).read_text())
pairs = {}
for f in ("kernel-rocq/KernelInstrs.v", "kernel-rocq/KernelData.v"):
    for a,b in load(f): pairs[int(a,16)] = int(b,16)
items = sorted(pairs.items())
print(f"image bytes: {len(items)}, range 0x{items[0][0]:x}..0x{items[-1][0]:x}", file=sys.stderr)
sys.setrecursionlimit(200000)
def tree(lo, hi):
    if lo >= hi: return ".leaf"
    mid = (lo+hi)//2; a,b = items[mid]
    return f"(.node {a} {b}#8 {tree(lo,mid)} {tree(mid+1,hi)})"
body = tree(0, len(items))
lean = f'''/-
GENERATED by tools/gen_kernel_image.py from the dumper's ELF image
(kernel-rocq/KernelInstrs.v + KernelData.v): the full loadable xv6 kernel image
(.text+.rodata+.data, {len(items)} bytes, 0x{items[0][0]:x}..0x{items[-1][0]:x}) as a shared
lookup so proof files import this instead of copying bytes. Balanced bisection tree.
-/
set_option maxHeartbeats 0
set_option maxRecDepth 1000000
namespace Xv6Iris.Model

inductive ImgTree where
  | leaf
  | node (addr : Nat) (byte : BitVec 8) (l r : ImgTree)

/-- Lookup the byte at `a` in a bisection tree (0 if absent). -/
def ImgTree.lookup : ImgTree → Nat → BitVec 8
  | .leaf, _ => 0#8
  | .node addr byte l r, a => if a < addr then l.lookup a else if a = addr then byte else r.lookup a

/-- The full loadable xv6 kernel image as a balanced bisection tree. -/
def kernelTree : ImgTree := {body}

/-- The xv6 kernel image byte at address `a` (0 outside the image: .bss/stack). -/
def kernelByte (a : Nat) : BitVec 8 := kernelTree.lookup a

end Xv6Iris.Model
'''
(ROOT/"lean/Xv6Iris/KernelImage.lean").write_text(lean)
print(f"wrote KernelImage.lean ({len(lean)} bytes)", file=sys.stderr)
