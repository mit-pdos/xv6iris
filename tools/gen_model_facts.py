#!/usr/bin/env python3
"""Generate MachCSL/ModelFacts.lean: one simp lemma per arm of the generated
model's `hartSupports` (a well-founded-recursive function that `decide` cannot
evaluate), so that `sail_norm` can reduce extension checks."""
import re, sys
src = open('model/Lean_RV64D/LeanRV64D/PlatformConfig.lean').read().splitlines()
start = next(i for i, l in enumerate(src) if l.startswith('def hartSupports ('))
arms = []
i = start + 2
cur = None
while i < len(src) and src[i] != '' and not src[i].startswith(('termination_by', 'decreasing_by')):
    l = src[i]
    m = re.match(r'^  \| \.(\w+) =>(.*)$', l)
    if m:
        if cur: arms.append(cur)
        cur = [m.group(1), m.group(2).strip()]
    elif cur is not None:
        cur[1] += ' ' + l.strip()
    i += 1
if cur: arms.append(cur)
# replicate the generated file's own namespace/open structure so that the arm
# texts elaborate exactly as they do in the model
header = [l for l in src[:start] if l.startswith(('open ', 'namespace ', 'noncomputable section'))]
out = ['-- AUTO-GENERATED by tools/gen_model_facts.py; do not edit.',
       'import MachCSL.SimpAttr', 'import LeanRV64D', '',
       'set_option maxRecDepth 10000', ''] + header + ['']
for name, rhs in arms:
    out.append('@[sail_facts] theorem hartSupports_%s : hartSupports extension.%s = (%s) := by' % (name, name, rhs))
    out.append('  rw [hartSupports.eq_def] <;> rfl')
    out.append('')
out.append('end Functions')
out.append('end LeanRV64D')
open('MachCSL/ModelFacts.lean', 'w').write('\n'.join(out) + '\n')
print('wrote %d lemmas' % len(arms), file=sys.stderr)
