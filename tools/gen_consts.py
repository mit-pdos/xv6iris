"""gen_consts.py -- GENERATE iris/KernelConsts.v: the image constants that a
hand-written file would otherwise transcribe.

WHY THIS EXISTS.  Most of the tree names an instruction through the generated
`Code<F>.v` layer, so an image bump costs it nothing.  A handful of files
instead need an image constant as a *Coq term* -- a `Definition`, not an
`instr` fact -- because specs UNIFY on it:

  * `ProcGeom.mycpu_ret` is the closed form of `&cpus` that mycpu's five
    instructions leave in a0.  Every per-CPU cell address, and every
    acquire / release / push_off / pop_off / myproc contract, is stated in
    that form so cells unify by name across call boundaries.  It therefore
    has to be a definition, and it embeds mycpu's `addi` immediate.
  * `WpDecode.w_ld` is `_entry`'s `ld sp, N(sp)` encoding word.
  * `BootChain.entry_got` is the address that `ld` reads from.
  * the four hand-written `Code*Aux.v` files name their own immediates.

Each of those was transcribed by hand, and each went stale on every bump --
surfacing NOT at its own definition but as an unhelpful failure in whatever
consumer happened to compile first: a bare `lia` "Cannot find witness" inside
`BootCarve.v`, or `Unable to unify "2147558352" with "2147558212"` inside
`ProcGeom.v` itself.  The diagnosis is nowhere near the defect, which is what
made them expensive.

So they are generated now, from the same dump the rest of the layer comes
from.  Adding one is a row in CONSTS below.

WHAT IS *NOT* HERE, deliberately: `RiscvLang.img_end` and `PageGeom.kmem_lo`.
Those two duplicate data the dumper already emits directly
(`KernelData.kernel_segments` and `KernelSyms.end_`), so they are defined over
it in place rather than round-tripped through a generator.
"""

import os

# ---------------------------------------------------------------------------
# Field extraction.  Only the forms the rows below actually use.
# ---------------------------------------------------------------------------


def _sext(v, bits):
    return v - (1 << bits) if v & (1 << (bits - 1)) else v


def imm_i(w):
    """I-type immediate as the 12-bit FIELD value (what the AST states)."""
    return (w >> 20) & 0xFFF


def imm_u(w):
    """U-type (auipc/lui) immediate as the 20-bit field value."""
    return (w >> 12) & 0xFFFFF


def imm_jal(w):
    """JAL immediate as the 21-bit field value the AST states."""
    b = lambda i: (w >> i) & 1
    v = (b(31) << 20)
    v |= ((w >> 21) & 0x3FF) << 1          # imm[10:1]
    v |= (b(20) << 11)                     # imm[11]
    v |= ((w >> 12) & 0xFF) << 12          # imm[19:12]
    return v


# ---------------------------------------------------------------------------
# The rows.  (coq_name, kind, symbol, offset, consumer, comment)
#
# kind:
#   'word32' the raw 32-bit encoding word
#   'imm_i'  I-type 12-bit immediate FIELD (unsigned, as the AST states it)
#   'imm_u'  U-type 20-bit immediate field
#   'imm_jal' JAL 21-bit immediate field
#   'pcrel'  the ADDRESS an auipc(off) / I-type(off+4) pair computes
# ---------------------------------------------------------------------------
CONSTS = [
    ("mycpu_cpus_addi", "imm_i", "mycpu", 0x12, "ProcGeom.mycpu_ret",
     "mycpu's [addi a0,a0,<imm>] completing &cpus (auipc at +0x0e)"),
    ("mycpu_cpus_auipc", "imm_u", "mycpu", 0x0E, "ProcGeom.mycpu_ret",
     "...and its auipc's upper immediate"),
    ("myproc_pidlock_addi", "imm_i", "myproc", 0x18, "ProofMyproc.mp_A4C",
     "myproc's [addi a4,a4,<imm>] completing &pid_lock (auipc at +0x14)"),
    ("myproc_pidlock_auipc", "imm_u", "myproc", 0x14, "ProofMyproc.mp_A4C",
     "...and its auipc's upper immediate"),
    ("entry_ld_word", "word32", "_entry", 0x04, "WpDecode.w_ld",
     "_entry's [ld sp,N(sp)] -- the GOT load that materializes stack0"),
    ("entry_got", "pcrel", "_entry", 0x00, "BootChain.entry_got",
     "...and the GOT slot address that auipc/ld pair reads"),
    ("kernelvec_jal_word", "word32", "kernelvec", 0x24, "CodeKernelvec.kv_dec19",
     "kernelvec's [jal ra,kerneltrap]"),
    ("kernelvec_jal_imm", "imm_jal", "kernelvec", 0x24, "CodeKernelvec.kv_i19",
     "...and its decoded 21-bit immediate"),
    ("start_main_addi", "imm_i", "start", 0x24, "CodeStartAux.si43",
     "start's [addi a5,a5,<imm>] completing &main (auipc at +0x20)"),
]

FILE_HEADER = """(* KernelConsts.v -- AUTO-GENERATED by tools/gen_code.py.  DO NOT EDIT BY HAND.

   The image constants that a hand-written file needs as a Coq TERM rather
   than as an [instr] fact -- because a spec unifies on the term.  Everything
   else names its instructions through the generated [Code<F>.v] layer and so
   costs nothing on an image bump; these used to be transcribed by hand, and
   each one went stale on every bump, surfacing far from its own definition.

   Regenerate with:  make gen-code
   Add one with:     a row in tools/gen_consts.py's CONSTS table.

   NOT here: [RiscvLang.img_end] and [PageGeom.kmem_lo], which duplicate data
   the dumper already emits ([KernelData.kernel_segments], [KernelSyms.end_])
   and are defined over it directly.                                       *)
From Stdlib Require Import ZArith.
Local Open Scope Z_scope.
"""


def compute(kind, sym, off, syms, word_at):
    base = syms[sym] + off
    if kind == "word32":
        return word_at(base, 4)
    if kind == "imm_i":
        return imm_i(word_at(base, 4))
    if kind == "imm_u":
        return imm_u(word_at(base, 4))
    if kind == "imm_jal":
        return imm_jal(word_at(base, 4))
    if kind == "pcrel":
        up = word_at(base, 4)
        lo = word_at(base + 4, 4)
        return base + (imm_u(up) << 12) + _sext(imm_i(lo), 12)
    raise ValueError("unknown kind %r" % kind)


def emit(iris, syms, by, word_at):
    """Write iris/KernelConsts.v.  Returns the number of constants emitted."""
    out = [FILE_HEADER]
    for name, kind, sym, off, consumer, comment in CONSTS:
        if sym not in syms:
            raise SystemExit(
                "gen_consts: symbol %r is not in the dump (row %r)" % (sym, name))
        v = compute(kind, sym, off, syms, word_at)
        out.append("")
        out.append("(* %s" % comment)
        out.append("   at [KernelSyms.%s + 0x%x]; consumed by %s *)" % (sym, off, consumer))
        out.append("Definition %s : Z := 0x%x." % (name, v))
    body = "\n".join(out) + "\n"
    path = os.path.join(iris, "KernelConsts.v")
    # Leave the file (and its mtime) alone when nothing moved, so a re-dump
    # that changes none of these rebuilds nothing -- same discipline as the
    # dumper's own outputs.
    if os.path.exists(path) and open(path).read() == body:
        return len(CONSTS), False
    open(path, "w").write(body)
    return len(CONSTS), True
