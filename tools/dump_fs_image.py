#!/usr/bin/env python3
"""Dump xv6's fs.img (the literal initial disk mkfs built) into Xv6/FsImgRaw.lean.

Rocq counterpart: kernel-rocq/FsImgRaw.v (tools/dump_elf.py --format
rocq-bin), read by iris/FsImgDisk.v.  Same bytes: the header records the md5,
and the Rocq dump of xv6-riscv 3e9926ea decodes to the same md5.

Encoding: one big-endian hex `Nat` per 1024-byte BLOCK (so byte `j` of the
block is the `j`-th pair of hex digits of its 2048-digit spelling, the way
MachCSL/KernelElf.lean's rows read), sixteen blocks to a page def, the pages
in one list.  A block lookup is two short list walks; a byte is one shift and
one `% 256` of a GMP number, cheap for `decide +kernel`.  An all-zero block
is spelled `0`.

Usage (from the repo root):
  tools/dump_fs_image.py --img PATH/fs.img [--rev REV] [--out Xv6/FsImgRaw.lean]
Build the image with the xv6 tree's own `make fs.img` (mkfs).  Rerun whenever
the user binaries change; Xv6/FsImgCheck.lean then rechecks it, and a check
that fails is a disagreement to FIX, never a statement to weaken.
"""
import argparse, hashlib

BSIZE, PAGE = 1024, 16

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--img', required=True)
    ap.add_argument('--out', default='Xv6/FsImgRaw.lean')
    ap.add_argument('--rev', default='unknown', help='the xv6-riscv commit fs.img was built from')
    a = ap.parse_args()
    img = open(a.img, 'rb').read()
    assert len(img) % BSIZE == 0, 'fs.img is not a whole number of blocks'
    nblk = len(img) // BSIZE
    blks = [img[i * BSIZE:(i + 1) * BSIZE] for i in range(nblk)]
    pages = [blks[i:i + PAGE] for i in range(0, nblk, PAGE)]
    md5 = hashlib.md5(img).hexdigest()
    with open(a.out, 'w') as f:
        f.write('-- AUTO-GENERATED by tools/dump_fs_image.py from %s (xv6-riscv %s, md5 %s); do not edit.\n'
                % (a.img, a.rev, md5))
        f.write('''/-
THE LITERAL mkfs IMAGE (Rocq `kernel-rocq/FsImgRaw.v`, `FsImgRaw.fsimg_hex`):
the %d bytes (%d blocks of BSIZE = 1024) xv6's `make fs.img` wrote.  No
file-format reasoning here; `Xv6/FsImgDisk.lean` turns it into the initial
disk and `Xv6/FsImgCheck.lean` proves it well formed.

One big-endian hex `Nat` per block (byte `j` is the `j`-th pair of digits; an
all-zero block is `0`), %d blocks to a page.  Every definition is
`@[irreducible]`: nothing but `decide +kernel` (which ignores the attribute)
may unfold it, and never inside a big-op.
-/

namespace Xv6.FsImgRaw

/-- The image's size in bytes (Rocq `FsImgRaw.fsimg_size`). -/
def fsimgSize : Nat := %d

''' % (len(img), nblk, PAGE, len(img)))
        for n, pg in enumerate(pages):
            f.write('@[irreducible] def page%d : List Nat := [\n' % n)
            lines = []
            for r, b in enumerate(pg):
                num = '0' if not any(b) else '0x' + b.hex()
                lines.append('  %s%s  -- block %d' % (num, ',' if r + 1 < len(pg) else '', n * PAGE + r))
            f.write('\n'.join(lines) + '\n]\n\n')
        f.write('/-- The image, page by page. -/\n@[irreducible] def pages : List (List Nat) :=\n  [%s]\n\n'
                % ',\n   '.join(', '.join('page%d' % m for m in range(k, min(k + 8, len(pages))))
                               for k in range(0, len(pages), 8)))
        f.write('''/-- Block `b` of the image, as its big-endian `Nat` (zero past the image). -/
@[irreducible] def blk (b : Nat) : Nat := (pages.getD (b / %d) []).getD (b %% %d) 0

end Xv6.FsImgRaw
''' % (PAGE, PAGE))
    print('%s: %d bytes, %d blocks, %d pages, md5 %s' % (a.out, len(img), nblk, len(pages), md5))

if __name__ == '__main__':
    main()
