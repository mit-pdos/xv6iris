#!/usr/bin/env bash
# Regenerate model-xv6iris/{rv64d.v,rv64d_types.v,riscv_extras.v} from a
# sail-riscv checkout, using this repo's own config and module list:
#
#   model-xv6iris/sail-config-rv64d.json   the resolved rv64d_v256_e64 config
#                                          with this project's deviations
#   model-xv6iris/sail-modules.txt         the module subset to compile
#   model-xv6iris/xv6iris_extras.v         HAND-WRITTEN; passed as a second
#                                          --coq-lib, NOT regenerated or
#                                          overwritten (see its header)
#
# See root README.md "Regenerating the Sail model" for background.
#
# Usage:
#   tools/regen_sail_model.sh [SAIL_RISCV_DIR]
#
# SAIL_RISCV_DIR defaults to $SAIL_RISCV_DIR in the environment, else
# ./sail-riscv (gitignored, cloned here on demand -- same treatment as
# xv6-riscv/).  The MODEL IS TAKEN FROM A FORK, zeldovich/sail-riscv, pinned at
# $SAIL_RISCV_REV (the fork's `xv6` branch); its deltas against riscv/sail-riscv
# upstream are the atomic PTE A/D-bit update, the `coq:` extern bindings on the
# platform hooks, and the matching `Axiom`s in handwritten_support/riscv_extras.v
# (all described in README.md).  A checkout that is not at the
# pinned revision is a warning, not an error: regenerating at another revision
# is a deliberate act (an upstream bump), and the proofs then have to be
# replayed against the new model.
#
# Requires: sail (with sail_coq_backend) on PATH, and coqc for the
# compile-check at the end.  No cmake: nothing in the model's .sail sources is
# generated by the build, so the source tree plus the files above is
# everything sail needs.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

SAIL_RISCV_URL="${SAIL_RISCV_URL:-https://github.com/zeldovich/sail-riscv}"
SAIL_RISCV_REV="${SAIL_RISCV_REV:-23dcf8fd923eb8a1958795393d2975632aa940b2}"
SAIL_RISCV_DIR="${1:-${SAIL_RISCV_DIR:-$REPO_ROOT/sail-riscv}}"

CONFIG_JSON="$REPO_ROOT/model-xv6iris/sail-config-rv64d.json"
MODULES_FILE="$REPO_ROOT/model-xv6iris/sail-modules.txt"
OUT_DIR="$REPO_ROOT/model-xv6iris"

if ! command -v sail >/dev/null 2>&1; then
  echo "error: 'sail' (with sail_coq_backend) not on PATH -- eval \$(opam env) first" >&2
  exit 1
fi

if [ ! -d "$SAIL_RISCV_DIR" ]; then
  echo "== Cloning $SAIL_RISCV_URL into $SAIL_RISCV_DIR =="
  git clone "$SAIL_RISCV_URL" "$SAIL_RISCV_DIR"
  git -C "$SAIL_RISCV_DIR" checkout --detach "$SAIL_RISCV_REV"
fi

have="$(git -C "$SAIL_RISCV_DIR" rev-parse HEAD 2>/dev/null || true)"
want="$(git -C "$SAIL_RISCV_DIR" rev-parse "$SAIL_RISCV_REV" 2>/dev/null || true)"
if [ -z "$want" ]; then
  echo "WARNING: $SAIL_RISCV_DIR does not have SAIL_RISCV_REV=$SAIL_RISCV_REV;" >&2
  echo "         try 'git -C $SAIL_RISCV_DIR fetch $SAIL_RISCV_URL'." >&2
elif [ "$have" != "$want" ]; then
  echo "WARNING: $SAIL_RISCV_DIR is at $have," >&2
  echo "         not the pinned SAIL_RISCV_REV=$want." >&2
  echo "         The model generated here will not be the one the proofs were" >&2
  echo "         written against.  Fix with:" >&2
  echo "         git -C $SAIL_RISCV_DIR checkout --detach $SAIL_RISCV_REV" >&2
fi

# The module subset, and the sail version the checkout asks for.  (The version
# is a floor sail itself enforces via --require-version; sail-riscv keeps it in
# cmake/sail_required_version.txt, older revisions in CMakeLists.txt.)
SAIL_MODULES="$(sed -e 's/#.*//' "$MODULES_FILE" | tr -s '[:space:]' ' ')"
if [ -z "${SAIL_MODULES// /}" ]; then
  echo "error: no modules read from $MODULES_FILE" >&2
  exit 1
fi
if [ -f "$SAIL_RISCV_DIR/cmake/sail_required_version.txt" ]; then
  SAIL_REQUIRED_VER="$(tr -d '[:space:]' < "$SAIL_RISCV_DIR/cmake/sail_required_version.txt")"
else
  SAIL_REQUIRED_VER="$(grep -m1 'set(SAIL_REQUIRED_VER' "$SAIL_RISCV_DIR/CMakeLists.txt" \
                        | sed -E 's/.*SAIL_REQUIRED_VER ([0-9.]+).*/\1/')"
fi
SAIL_HAVE_VER="$(sail --version | sed -E 's/^Sail ([0-9.]+).*/\1/')"
if [ "$SAIL_REQUIRED_VER" != "$SAIL_HAVE_VER" ]; then
  # sail's --require-version is a hard floor, so pass the version we HAVE and
  # let generation fail loudly if the sources really need something newer.
  echo "note: $SAIL_RISCV_DIR asks for sail $SAIL_REQUIRED_VER, this is sail $SAIL_HAVE_VER;"
  echo "      generating with --require-version $SAIL_HAVE_VER."
  SAIL_REQUIRED_VER="$SAIL_HAVE_VER"
fi

echo "== Running sail (--coq) with $(basename "$CONFIG_JSON") =="
echo "   modules: $SAIL_MODULES"
TMP_OUT="$(mktemp -d)"
CHECK_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_OUT" "$CHECK_DIR"' EXIT
(
  cd "$SAIL_RISCV_DIR/model"
  sail --strict-var --strict-bitvector --strict-exponentials \
    --require-version "$SAIL_REQUIRED_VER" \
    --memo-z3-path "$SAIL_RISCV_DIR/build/model/sail_smt_cache" \
    --dcoq-undef-axioms --coq --coq-lib xv6iris_extras --coq-lib riscv_extras \
    --coq-output-dir "$TMP_OUT" \
    -o rv64d \
    --config "$CONFIG_JSON" \
    $SAIL_MODULES \
    riscv.sail_project
)

# The compile-check is what catches a DRIFTED xv6iris_extras.v: the `coq:`
# bindings in the sail-riscv fork make sail emit no signature for those hooks,
# so if this repo's realisations no longer match the types sail expects at the
# call sites, rv64d.v fails to compile HERE rather than somewhere in iris/.
echo "== Compile-checking the regenerated model =="
if command -v coqc >/dev/null 2>&1; then
  cp "$TMP_OUT/rv64d.v" "$TMP_OUT/rv64d_types.v" \
     "$SAIL_RISCV_DIR/handwritten_support/riscv_extras.v" \
     "$OUT_DIR/xv6iris_extras.v" "$CHECK_DIR/"
  ( cd "$CHECK_DIR" \
      && coqc -R . Riscv riscv_extras.v \
      && coqc -R . Riscv rv64d_types.v \
      && coqc -R . Riscv xv6iris_extras.v \
      && coqc -R . Riscv rv64d.v )
  echo "   OK: compiles clean under coqc"
else
  echo "   warning: coqc not found, skipping compile-check" >&2
fi

echo "== Installing into $OUT_DIR =="
cp "$TMP_OUT/rv64d.v" "$TMP_OUT/rv64d_types.v" "$OUT_DIR/"
cp "$SAIL_RISCV_DIR/handwritten_support/riscv_extras.v" "$OUT_DIR/"
# xv6iris_extras.v is deliberately NOT copied back: it is this repo's file.
echo "Done.  Review 'git diff model-xv6iris/' and run 'make model'; every"
echo "difference in rv64d.v is a change the iris/ proofs may have to absorb."
