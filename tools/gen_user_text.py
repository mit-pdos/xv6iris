#!/usr/bin/env python3
"""Emit a user program's text search tree and its text facts (union DU3), from
the instruction list of Xv6/User/<P>Image.lean (run by tools/dump_user_elf.py):

  Xv6/User/<P>Tree.lean  `Xv6.User.<P>.tree : UTextTree`, a balanced tree
                          literal keyed by address (tools/gen_text_tree.py's
                          shape, over `UInstr`);
  Xv6/User/<P>Text.lean  `<P>.tree_toList` (the tree IS the dumped text),
                          `<P>.text_in_code` (every instruction's bytes are in
                          the R-X segment's file bytes), `<P>.code_wf`/`data_wf`
                          and `<P>.textOk : UTextOk <P>.tree <P>.code.byte`,
                          the one premise `Xv6.UserText.utext_find` takes.
                          All by `decide +kernel`, once per image.

Usage: tools/gen_user_text.py --image Xv6/User/<P>Image.lean --module P [--outdir Xv6/User] [--chunk 512]
"""
import argparse, os, re

ENTRY_RE = re.compile(r'^\s*⟨(0x[0-9a-f]+), (\d+), (0x[0-9a-f]+)⟩,?\s*$')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--image', required=True)
    ap.add_argument('--module', required=True)
    ap.add_argument('--outdir', default='Xv6/User')
    ap.add_argument('--chunk', type=int, default=512)
    a = ap.parse_args()
    P = a.module
    entries = []
    for line in open(a.image):
        m = ENTRY_RE.match(line)
        if m:
            entries.append((m.group(1), m.group(2), m.group(3)))
    assert entries, 'no instructions found'
    defs = []

    def lit(lo, hi):
        if lo >= hi:
            return '.leaf'
        mid = (lo + hi) // 2
        ad, w, e = entries[mid]
        return '(.node %s ⟨%s, %s, %s⟩ %s)' % (lit(lo, mid), ad, w, e, lit(mid + 1, hi))

    def build(lo, hi):
        if hi - lo <= a.chunk:
            name = 'treeChunk%d' % len(defs)
            defs.append((name, lit(lo, hi)))
            return name
        mid = (lo + hi) // 2
        left = build(lo, mid)
        right = build(mid + 1, hi)
        ad, w, e = entries[mid]
        return '(.node %s ⟨%s, %s, %s⟩ %s)' % (left, ad, w, e, right)

    top = build(0, len(entries))
    tree = os.path.join(a.outdir, '%sTree.lean' % P)
    with open(tree, 'w') as f:
        f.write('-- AUTO-GENERATED by tools/gen_user_text.py from %s; do not edit.\n' % a.image)
        f.write('-- The text of `%s` as an address-keyed balanced search tree (see %sText.lean).\n'
                % (P.lower(), P))
        f.write('import Xv6.UserTextDefs\n\nnamespace Xv6.User.%s\n\nopen Xv6.User\n\n' % P)
        f.write('section\nset_option maxRecDepth 4096\n\n')
        for name, body in defs:
            f.write('def %s : UTextTree :=\n  %s\n\n' % (name, body))
        f.write('/-- All %d instructions of `%s`\'s text, searchable by address. -/\n' % (len(entries), P.lower()))
        f.write('def tree : UTextTree :=\n  %s\n\nend\n\nend Xv6.User.%s\n' % (top, P))
    text = os.path.join(a.outdir, '%sText.lean' % P)
    with open(text, 'w') as f:
        f.write('-- AUTO-GENERATED by tools/gen_user_text.py; do not edit.\n')
        f.write('/-\nThe text facts of `%s` (union DU3): the search tree is the dumped text, and\n'
                'every instruction\'s bytes sit in the R-X segment\'s file bytes -- the one\n'
                'premise (`textOk`) of the generic fetch lemma `Xv6.UserText.utext_find`.\n'
                'Checked by the kernel alone (`decide +kernel`), once per image.\n-/\n' % P.lower())
        f.write('import Xv6.User.%sImage\nimport Xv6.User.%sTree\n\nnamespace Xv6.User.%s\n\nopen Xv6.User\n\n'
                % (P, P, P))
        f.write('theorem code_wf : code.wf := by decide +kernel\n\ntheorem data_wf : data.wf := by decide +kernel\n\n')
        f.write('set_option maxRecDepth 100000 in\n'
                '/-- The search tree is the dumped text. -/\n'
                'theorem tree_toList : tree.toList = text := by decide +kernel\n\n')
        f.write('/-- Every dumped instruction is the R-X segment\'s bytes at its address. -/\n'
                'theorem text_in_code : text.all (instrIn code.byte) = true :=\n'
                '  scanIn_instrIn code code_wf text (by decide +kernel)\n\n')
        f.write('/-- The fetch premise of `Xv6.UserText.utext_find` at `%s`. -/\n'
                'theorem textOk : UTextOk tree code.byte := UTextOk.of_toList tree text code.byte tree_toList text_in_code\n\n'
                % P.lower())
        f.write('end Xv6.User.%s\n' % P)
    print('wrote %s (%d instructions, %d subtrees) and %s' % (tree, len(entries), len(defs), text))


if __name__ == '__main__':
    main()
