#!/usr/bin/env python3
"""Dump the xv6 kernel ELF's text section into Lean data (Xv6/KernelImage.lean).

Each instruction becomes a triple (address, width in bytes, encoding), where the
encoding is exactly the integer the Sail decoder is given (the little-endian
assembled instruction word), so no byte swapping is needed on the Lean side.
Symbols are emitted as `KernelSyms.<name> : Nat`.

Usage: tools/dump_kernel.py [--kernel PATH] [--out PATH] [--objdump OBJDUMP]
"""
import argparse, os, re, subprocess, sys

INSTR_RE = re.compile(r'^\s*([0-9a-f]+):\t([0-9a-f ]+?)\s*(?:\t(.*))?$')
SYM_RE = re.compile(r'^\s*([0-9a-f]+) <([A-Za-z0-9_.$]+)>:$')

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--kernel', default='xv6-riscv/kernel/kernel')
    ap.add_argument('--out', default='Xv6/KernelImage.lean')
    ap.add_argument('--objdump', default='riscv64-linux-gnu-objdump')
    ap.add_argument('--chunk', type=int, default=500)
    ap.add_argument('--rev', default=None, help='the xv6-riscv commit the kernel was built from (recorded in the header)')
    a = ap.parse_args()

    # `-z`: zero padding is disassembled too (objdump otherwise folds it into
    # `...`); only the FIRST `c.unimp` halfword of each zero run is kept below,
    # so a compressed instruction at a 4-aligned pc just before the padding
    # still has its following halfword in the image (the fetch reads 4 bytes;
    # see `textDecodeWith`).
    out = subprocess.run([a.objdump, '-d', '-z', '--section=.text', a.kernel],
                         check=True, capture_output=True, text=True).stdout
    instrs, syms = [], []
    prev_zero_end = None
    for line in out.splitlines():
        m = SYM_RE.match(line)
        if m:
            syms.append((m.group(2), int(m.group(1), 16)))
            continue
        m = INSTR_RE.match(line)
        if not m:
            continue
        addr = int(m.group(1), 16)
        words = m.group(2).split()
        # objdump prints one field per instruction (the assembled word)
        for w in words:
            width = len(w) // 2
            enc = int(w, 16)
            zero = width == 2 and enc == 0
            if not (zero and prev_zero_end == addr):
                instrs.append((addr, width, enc, (m.group(3) or '').strip()))
            prev_zero_end = addr + 2 if zero else None
            addr += width

    with open(a.out, 'w') as f:
        rev = a.rev or subprocess.run(['git', '-C', os.path.dirname(os.path.dirname(os.path.abspath(a.kernel))),
                              'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip() or 'unknown'
        f.write('-- AUTO-GENERATED by tools/dump_kernel.py from %s (xv6-riscv %s); do not edit.\n' % (os.path.basename(a.kernel), rev))
        f.write('-- The xv6 kernel text section: (address, width in bytes, instruction word).\n')
        f.write('import MachCSL.SimpAttr\n\nnamespace Xv6.Kernel\n\n')
        f.write('/-- One instruction of the kernel text. -/\n')
        f.write('structure KInstr where\n  addr : Nat\n  width : Nat\n  enc : Nat\n  deriving Repr, DecidableEq\n\n')
        chunks = [instrs[i:i+a.chunk] for i in range(0, len(instrs), a.chunk)]
        for ci, ch in enumerate(chunks):
            f.write('def textChunk%d : List KInstr := [\n' % ci)
            f.write(',\n'.join('  -- %s\n  ⟨0x%x, %d, 0x%0*x⟩' % (asm.replace('\n', ' '), ad, w, 2*w, e) for ad, w, e, asm in ch))
            f.write('\n]\n\n')
        f.write('/-- All %d instructions of the kernel text, in address order. -/\n' % len(instrs))
        f.write('def text : List KInstr :=\n  ' + ' ++ '.join('textChunk%d' % i for i in range(len(chunks))) + '\n\n')
        f.write('end Xv6.Kernel\n\nnamespace MachCSL.KernelSyms\n\n')
        seen = set()
        for name, addr in syms:
            lean = name.replace('.', '_').replace('$', '_')
            if lean in seen or not re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', lean):
                continue
            seen.add(lean)
            f.write('def %s : Nat := 0x%x\n' % ('«%s»' % lean, addr))
        # the data symbols (.data/.bss/.rodata objects) from the symbol table
        f.write('\n-- data symbols (.data, .bss, .rodata, .got)\n')
        symtab = subprocess.run([a.objdump, '-t', a.kernel], check=True, capture_output=True, text=True).stdout
        dsyms = []
        for line in symtab.splitlines():
            m = re.match(r'^([0-9a-f]{16}) (.{7}) (\S+)\t([0-9a-f]{16}) (\S+)$', line)
            if m and (m.group(3) in ('.data', '.bss', '.rodata', '.got') or (m.group(3) == '.text' and 'F' not in m.group(2))):
                lean = m.group(5).replace('.', '_').replace('$', '_')
                if lean in seen or not re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', lean):
                    continue
                seen.add(lean)
                dsyms.append((lean, int(m.group(1), 16), int(m.group(4), 16)))
        for lean, addr, size in sorted(dsyms, key=lambda x: x[1]):
            f.write('def %s : Nat := 0x%x  -- size 0x%x\n' % ('«%s»' % lean, addr, size))
        f.write('\nend MachCSL.KernelSyms\n')
        # the NUL-terminated strings of .rodata, named by content
        rod = subprocess.run([a.objdump, '-s', '-j', '.rodata', a.kernel], check=True, capture_output=True, text=True).stdout
        base, data = None, bytearray()
        for line in rod.splitlines():
            m = re.match(r'^ ([0-9a-f]+) ((?:[0-9a-f]{2,8} ?){1,4})\s', line)
            if m:
                if base is None: base = int(m.group(1), 16)
                for w in m.group(2).split(): data += bytes.fromhex(w)
        f.write('\n-- The NUL-terminated strings of `.rodata`, by content (a duplicate gets a `_2`, `_3`, ... suffix).\n')
        f.write('namespace MachCSL.KernelStr\n\n')
        names = {}
        i = 0
        while i < len(data):
            j = data.find(b'\0', i)
            if j < 0: break
            sbytes = bytes(data[i:j])
            if 1 <= len(sbytes) <= 64 and all(32 <= c < 127 or c in (9, 10, 13) for c in sbytes):
                text = sbytes.decode('ascii').replace('\\', '\\\\').replace('\n', '\\n').replace('\t', '\\t').replace('\r', '\\r').replace('»', '')
                key = text; k = 1
                while key in names:
                    k += 1; key = '%s_%d' % (text, k)
                names[key] = base + i
                f.write('/-- `%s` at `0x%x` -/\ndef «%s» : Nat := 0x%x\n' % (repr(sbytes)[2:-1].replace('-/', '- /'), base + i, key, base + i))
            i = j + 1
        f.write('\nend MachCSL.KernelStr\n')
        # the same symbols as 64-bit addresses: what the proofs name (`KA.«f» + 0x1c#64`)
        f.write('\n/-! The symbols as kernel ADDRESSES (`BitVec 64`): every address a proof\nnames is one of these plus an offset (`KA.«kinit» + 0x10#64`).  Plain\ndefinitions: the normalisers keep them folded, `decide`/`rfl` see through\nthem. -/\nnamespace MachCSL.KA\n\n')
        for lean in sorted(seen):
            f.write('def %s : BitVec 64 := BitVec.ofNat 64 KernelSyms.%s\n' % ('«%s»' % lean, '«%s»' % lean))
            f.write('@[k_addr] theorem %s : BitVec.ofNat 64 KernelSyms.%s = %s := rfl\n' % ('«%s_ofNat»' % lean, '«%s»' % lean, '«%s»' % lean))
        f.write('\nend MachCSL.KA\n\n/-! The `.rodata` strings as addresses. -/\nnamespace MachCSL.KStr\n\n')
        for key in names:
            f.write('def «%s» : BitVec 64 := BitVec.ofNat 64 KernelStr.«%s»\n' % (key, key))
            f.write('@[k_addr] theorem «%s_ofNat» : BitVec.ofNat 64 KernelStr.«%s» = «%s» := rfl\n' % (key, key, key))
        f.write('\nend MachCSL.KStr\n')
    print('wrote %s: %d instructions, %d symbols' % (a.out, len(instrs), len(seen)), file=sys.stderr)
    # The search-tree form proofs look instructions up in (KernelText.lean proves it equal).
    subprocess.check_call([os.path.join(os.path.dirname(os.path.abspath(__file__)), 'gen_text_tree.py'),
                           '--image', a.out, '--out', os.path.join(os.path.dirname(a.out), 'KernelTree.lean')])

if __name__ == '__main__':
    main()
