#!/usr/bin/env python3
# Regenerate Xv6Iris/RealRegs.lean from the pulled-in model's `Register` enum:
# a `Nat` key for the 180-constructor `Register`, a left inverse (so injectivity
# is `cases <;> rfl`, not 180² cases), and `Ord`/`TransOrd`/`LawfulEqOrd`
# instances that delegate to `Nat` through `regKey` — the `LawfulFiniteMap`
# iris-lean's `gen_heap` needs to key registers by `Register`.
#
#   run after `make model`:  python3 tools/gen-regkeys.py
import re, sys, pathlib

LEAN = pathlib.Path(__file__).resolve().parent.parent
DEFS = LEAN / ".model/sail-riscv-lean/LeanRV64D/Defs.lean"
OUT = LEAN / "Xv6Iris/RealRegs.lean"

defs = DEFS.read_text()
m = re.search(r'^inductive Register : Type where\n(.*?)\n  deriving', defs, re.S | re.M)
ctors = [l.strip()[2:].strip() for l in m.group(1).splitlines() if l.strip().startswith('|')]
assert len(ctors) == 180, f"expected 180 Register constructors, got {len(ctors)}"

# Parse `RegisterType` to classify each register as a bit-vector or structured.
rt = re.search(r'^abbrev RegisterType : Register → Type\n(.*?)\n(?=abbrev |def |inductive |structure |instance |open |namespace |\Z)', defs, re.S | re.M)
regty = dict(re.findall(r'^\s*\|\s*\.(\w+)\s*=>\s*(.+)$', rt.group(1), re.M))
def is_bitvec(name):
    r = regty[name].strip()
    if r.startswith('(') and r.endswith(')'): r = r[1:-1].strip()
    return r.startswith('BitVec')

L = []
L.append('''/-
GENERATED by tools/gen-regkeys.py (do not edit by hand) + a hand-written instance
tail. A `Nat` key for the real model's 180-constructor `Register` enum, with a
left inverse so injectivity is `cases <;> rfl`, and `Ord`/`TransOrd`/`LawfulEqOrd`
instances that delegate to `Nat` via `regKey` — giving the `LawfulFiniteMap` that
iris-lean's `gen_heap` needs to key registers by `Register`.
Non-module (imports the non-module model).
-/
import Sail
import LeanRV64D

open LeanRV64D.Defs (Register RegisterType)

namespace Xv6Iris.Model
''')
L.append('def regKey : Register → Nat')
L += [f'  | .{c} => {i}' for i, c in enumerate(ctors)]
L.append('')
L.append('def regUnkey : Nat → Register')
L += [f'  | {i} => .{c}' for i, c in enumerate(ctors)]
L.append(f'  | _ => .{ctors[0]}')
L.append('''
theorem regKey_leftInv (r : Register) : regUnkey (regKey r) = r := by
  cases r <;> rfl

theorem regKey_injective : Function.Injective regKey :=
  Function.LeftInverse.injective regKey_leftInv

/-- `Ord Register` by comparing `Nat` keys; the order laws delegate to `Nat`
through `regKey` (so no 180-constructor case analysis). -/
instance instOrdRegister : Ord Register where
  compare a b := compare (regKey a) (regKey b)

instance : Std.OrientedCmp (compare (α := Register)) where
  eq_swap {a b} := by
    show compare (regKey a) (regKey b) = (compare (regKey b) (regKey a)).swap
    exact Std.OrientedCmp.eq_swap

instance : Std.TransOrd Register where
  isLE_trans {a b c} := by
    show (compare (regKey a) (regKey b)).isLE = true →
         (compare (regKey b) (regKey c)).isLE = true →
         (compare (regKey a) (regKey c)).isLE = true
    exact Std.TransCmp.isLE_trans

instance : Std.ReflCmp (compare (α := Register)) where
  compare_self {a} := by
    show compare (regKey a) (regKey a) = Ordering.eq
    exact Std.ReflCmp.compare_self

instance : Std.LawfulEqOrd Register where
  eq_of_compare {a b} h :=
    regKey_injective (Std.LawfulEqCmp.eq_of_compare (cmp := (compare : Nat → Nat → Ordering)) h)
''')
# encode/decode: a uniform `BitVec 64` view of each register (the user's design).
# Bit-vector registers (167) use `setWidth` (narrow ⇒ high bits irrelevant; the
# 64-bit ones — GPRs, PC, scalar CSRs — are the identity); structured registers
# (13) get a junk/default value (they're not exposed via the uniform points-to).
L.append('''/-- Encode a register's real value into the uniform `BitVec 64` heap cell. -/
noncomputable def encReg : (r : Register) → RegisterType r → BitVec 64''')
for c in ctors:
    L.append(f'  | .{c}, v => v.setWidth 64' if is_bitvec(c) else f'  | .{c}, _ => 0#64')
L.append('''
/-- Decode a heap cell back to a register's real value (inverse of `encReg` on
the 64-bit registers; `setWidth` truncates for narrower ones). -/
noncomputable def decReg : (r : Register) → BitVec 64 → RegisterType r''')
for c in ctors:
    L.append(f'  | .{c}, v => v.setWidth _' if is_bitvec(c) else f'  | .{c}, _ => default')
L.append('''
end Xv6Iris.Model''')
OUT.write_text('\n'.join(L) + '\n')
print(f"wrote {OUT} ({len(ctors)} registers)")
