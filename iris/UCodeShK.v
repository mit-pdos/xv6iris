(* The vpn of an address IS the vpn of its page base.  This is the
   arithmetic the two projections below need, and having it ONCE is what
   lets a per-pc proof state no svpn identity of its own -- UCodeEcho.v
   could do that identification with a [vm_compute] per instance only
   because its whole image was page 0. *)
Lemma shk_svpn_page (a : Z) :
  0 <= a < 274877906944 ->
  svpn_of (mword_of_int a : mword 64)
    = svpn_of (mword_of_int (4096 * (a / 4096)) : mword 64).
Proof.
  intros [ Hlo Hhi ].
  assert (Hq : 0 <= 4096 * (a / 4096) <= a).
  { split.
    - apply Z.mul_nonneg_nonneg; [ lia | apply Z.div_pos; lia ].
    - apply Z.mul_div_le; lia. }
  apply bv_eq.
  rewrite (svpn_of_unsigned_lo (mword_of_int a : mword 64))
    by (rewrite uint_unsigned, moi64_small; lia).
  rewrite (svpn_of_unsigned_lo (mword_of_int (4096 * (a / 4096)) : mword 64))
    by (rewrite uint_unsigned, moi64_small; lia).
  rewrite !uint_unsigned, !moi64_small by lia.
  rewrite !Z.shiftr_div_pow2 by lia.
  change (2 ^ 12) with 4096.
  rewrite (Z.mul_comm 4096 (a / 4096)), Z.div_mul by lia. reflexivity.
Qed.

(* The pure page-table premise: each of the 2 page(s) of the executable
   segment is mapped with a leaf that permits instruction FETCH and a user
   data LOAD.  Quantified over the page INDEX rather than one field per
   page, so the record does not change shape when a program grows; page [i]
   is user va [4096*i], because a user program is linked at 0
   (user/user.ld).  The load half is what makes a .rodata string sharing a
   text page a legal [write] buffer. *)
Record shk_text_layout (pt : uptd) : Prop := ShkTextLayout {
  stl_pg : forall i : Z, 0 <= i < 2 ->
    exists w : mword 64,
      ud_um pt !! svpn_of (mword_of_int (4096 * i) : mword 64) = Some w /\
      uleaf_ok (InstructionFetch tt) w /\ uleaf_ok (Load Data) w
}.

(* the fetch projection, in exactly the shape [UmodeMem.uva_fetch_leaf]
   wants -- it takes the page index from the address itself *)
Lemma shk_text_layout_fetch (pt : uptd) (off : Z) :
  shk_text_layout pt -> 0 <= off < 8192 ->
  uva_fetch_leaf pt (mword_of_int off).
Proof.
  intros [ Hpg ] Hoff.
  destruct (Hpg (off / 4096)
              ltac:(split; [ apply Z.div_pos; lia
                           | apply Z.div_lt_upper_bound; lia ]))
    as (w & Hl & Hok & _).
  exists w. rewrite (shk_svpn_page off ltac:(lia)). split; assumption.
Qed.

(* the same leaf, in the shape [UmodeAbi.uv_rd]'s [urd_leaf] field wants *)
Lemma shk_text_layout_load (pt : uptd) (a : Z) :
  shk_text_layout pt -> 0 <= a < 8192 ->
  exists w : mword 64,
    ud_um pt !! svpn_of (mword_of_int a : mword 64) = Some w /\
    uleaf_ok (Load Data) w.
Proof.
  intros [ Hpg ] Ha.
  destruct (Hpg (a / 4096)
              ltac:(split; [ apply Z.div_pos; lia
                           | apply Z.div_lt_upper_bound; lia ]))
    as (w & Hl & _ & Hok).
  exists w. rewrite (shk_svpn_page a ltac:(lia)). split; assumption.
Qed.

(* ONE readable byte of the loaded data image, on a text page -- the
   address is a parameter, so each string literal a program hands to
   [write] costs one line at the call site. *)
Lemma shk_rodata_rd1 (pt : uptd) (M : gmap Z (bv 8)) (a : Z) (b : bv 8) :
  shk_text_layout pt -> shk_data_sub M ->
  0 <= a < 8192 ->
  ShData.sh_data !! a = Some b ->
  uv_rd pt M a 1.
Proof.
  intros Hl Hsub Ha Hb. constructor.
  - lia.
  - lia.
  - change (2 ^ 38) with 274877906944. lia.
  - intros j Hj. assert (Hj0 : j = 0) by lia. subst j.
    rewrite Z.add_0_r. exact (shk_text_layout_load pt a Hl Ha).
  - intros j Hj. assert (Hj0 : j = 0) by lia. subst j.
    rewrite Z.add_0_r. exists b. exact (Hsub a b Hb).
Qed.

