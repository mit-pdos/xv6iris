  (* 0x9d6  c.addi4spn s0,sp,16  (RVC, 2 mod 4) *)
  Lemma uis_shk_9d6 (g : gname) :
    shk_code g -∗
    uinstr_is g (mword_of_int 0x9d6) true
      (C_ADDI4SPN (Cregidx (mword_of_int 0), mword_of_int 4 : mword 8)).
