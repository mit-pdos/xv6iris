  (* §3 Where the catalog comes from.                                      *)
  (* =================================================================== *)

  (* [shm_code] is defined above, at the top of the section, because every
     per-pc lemma consumes it. This is its INTRODUCTION, and the ONE place in
     the whole development where the program's bytes meet the process image:
     the entry hands out [utext_all gt M pm] -- the text half of the heap,
     over the image the kernel actually loaded -- and the two section
     hypotheses say that image contains the dump ([shm_text_sub]) and that
     the executable segment is X-and-not-W ([Hx]), which is what puts those
     bytes in the TEXT half rather than the data one. Both are discharged
     HERE, once, instead of in each of the 150 per-pc lemmas. *)

  (* AND THE READ-ONLY IMAGE BESIDE IT. A program's string LITERALS are not
     in [ShInstrs.sh_bytes] and they are not in the data half either: .rodata
     shares the EXECUTABLE segment's pages, so its bytes are X-and-not-W and
     the heap files them under [γt] exactly as it files the code. This
     program's literals land at 0x1264..0x1c74, inside the R-X segment, and a
     printf-family walk LOADS them one byte at a time. This is the part of
     [ShData.sh_data] that lands there -- everything below the end of the
     executable segment -- and [UserHeap.utext_str_of_img] cuts a literal out
     of it at a concrete base and length. *)
  Definition shm_ro : gmap Z (bv 8) :=
    filter (fun kv => (kv.1 < 8192)%Z) ShData.sh_data.

  Definition shm_rodata (g : gname) : iProp Σ := utext_img g shm_ro.

  Global Instance shm_rodata_persistent g : Persistent (shm_rodata g).
  Proof using . apply _. Qed.

  Global Typeclasses Opaque shm_rodata.

  Lemma shm_rodata_of_text : utext_all gt M pm -∗ shm_rodata gt.
  Proof.
    assert (Hin : forall (a : Z) (b : bv 8),
               shm_ro !! a = Some b -> M !! a = Some b).
    { intros a b Hb. apply map_lookup_filter_Some in Hb as [Hb _].
      exact (Hsub2 a b Hb). }
    assert (Hp : forall a : Z, is_Some (shm_ro !! a) ->
                   ux_addr pm a /\ ~ uw_addr pm a).
    { intros a [b Hb]. apply map_lookup_filter_Some in Hb as [Hb Hlt].
      apply Hx.
      pose proof (shm_data_key_nonneg a b Hb) as Hge.
      simpl in Hlt. lia. }
    iIntros "#Ht". rewrite /shm_rodata.
    iApply (utext_img_of_all gt M pm shm_ro Hin Hp with "Ht").
  Qed.

  Lemma shm_code_of_text : utext_all gt M pm -∗ shm_code gt.
  Proof.
    assert (Hin : forall (a : Z) (b : bv 8),
               ShInstrs.sh_bytes !! a = Some b -> M !! a = Some b)
      by exact Hsub.
    assert (Hp : forall a : Z, is_Some (ShInstrs.sh_bytes !! a) ->
                   ux_addr pm a /\ ~ uw_addr pm a).
    { intros a [b Hb]. apply Hx.
      pose proof (shm_bytes_key_lt a b Hb) as Hlt.
      pose proof (shm_bytes_key_nonneg a b Hb) as Hge. lia. }
    iIntros "#Ht". rewrite /shm_code.
    iApply (utext_img_of_all gt M pm ShInstrs.sh_bytes Hin Hp with "Ht").
  Qed.

End UCodeShM.
