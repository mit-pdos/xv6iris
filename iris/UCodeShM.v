(* [M] contains the dumped text -- the generic image inclusion (UmodeAbi.v)
   at this program's text bytes.  An inclusion (not an equality), so a
   process image carrying rodata/bss/stack/argv on top still qualifies. *)
Definition shm_text_sub (M : gmap Z (bv 8)) : Prop :=
  uimg_sub ShInstrs.sh_bytes M.

(* ... and the dumped RODATA/data.  A string literal a program hands to
   [write] lives here, not in the text map, so the readable-window lemma
   below needs THIS inclusion. *)
Definition shm_data_sub (M : gmap Z (bv 8)) : Prop :=
  uimg_sub ShData.sh_data M.

(* ... and the two together, so a spec carries ONE image premise.  The
   per-pc [uinstr] facts below deliberately take only [shm_text_sub]: an
   instruction fetch never reads the data half. *)
Definition shm_img_sub (M : gmap Z (bv 8)) : Prop :=
  shm_text_sub M /\ shm_data_sub M.

Lemma shm_img_text (M : gmap Z (bv 8)) : shm_img_sub M -> shm_text_sub M.
Proof. intros [ H _ ]. exact H. Qed.
Lemma shm_img_data (M : gmap Z (bv 8)) : shm_img_sub M -> shm_data_sub M.
Proof. intros [ _ H ]. exact H. Qed.

(* ---- the KEY RANGE of each dumped map ------------------------------- *)
(* The bounds are COMPUTED from the dump (text keys stop at 0x127f, data keys
   at 0x200f) and rounded up to the next page, which is the shape the users of
   the fact want: [UmodeAbi.uM_only_img] asks exactly "the written window is
   disjoint from every key of [img]", and the windows a program writes are
   its stack, which starts at a page boundary above the image. *)

Lemma list_key_lt {A : Type} (L : list (Z * A)) (B k : Z) (b : A) :
  forallb (fun kv => Z.ltb (fst kv) B) L = true -> In (k, b) L -> k < B.
Proof.
  induction L as [ | x xs IH ]; cbn [forallb In]; [ tauto | ].
  intros HF [ Hx | Hin ].
  - apply andb_prop in HF as [ H1 _ ]. subst x. cbn in H1.
    apply Z.ltb_lt in H1. exact H1.
  - apply andb_prop in HF as [ _ H2 ]. exact (IH H2 Hin).
Qed.

(* ...and the LOWER bound, which the same [forallb] decides.  [Hx] and
   every other page-range hypothesis is two-sided, so a key fact that
   only bounds above leaves [0 <= k] for [lia] to invent out of nothing. *)
Lemma list_key_nonneg {A : Type} (L : list (Z * A)) (k : Z) (b : A) :
  forallb (fun kv => Z.leb 0 (fst kv)) L = true -> In (k, b) L -> 0 <= k.
Proof.
  induction L as [ | x xs IH ]; cbn [forallb In]; [ tauto | ].
  intros HF [ Hx | Hin ].
  - apply andb_prop in HF as [ H1 _ ]. subst x. cbn in H1.
    apply Z.leb_le in H1. exact H1.
  - apply andb_prop in HF as [ _ H2 ]. exact (IH H2 Hin).
Qed.

